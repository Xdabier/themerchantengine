interface Frontmatter {
  title: string;
  description: string;
  primaryQuery: string;
  schema: 'TechArticle' | 'HowTo' | 'FAQPage';
}

/** YAML-safe: every value is a JSON string, which YAML reads as a double-quoted scalar. */
function frontmatter(front: Frontmatter, updated: string): string {
  return [
    '---',
    `title: ${JSON.stringify(front.title)}`,
    `description: ${JSON.stringify(front.description)}`,
    `primaryQuery: ${JSON.stringify(front.primaryQuery)}`,
    `updated: ${updated}`,
    `schema: ${front.schema}`,
    '---',
  ].join('\n');
}

/** The body of a committed page from its marker on, so two renders compare on content alone; null when the marker is absent. */
function bodyOf(page: string): string | null {
  const at = page.indexOf(PAGE_MARKER);
  return at < 0 ? null : page.slice(at).replace(/\r\n/g, '\n');
}

/**
 * Renders a page and keeps the committed page's `updated` date while the body
 * is unchanged, so a run on another day is byte-identical. `committedDir` is
 * where the last committed copy lives, which is the real reference tree even
 * when the output goes to a scratch directory.
 */
export function renderPage(front: Frontmatter, body: string, committedFile: string): string {
  const fresh = `${PAGE_MARKER}\n\n${body.trimEnd()}\n`;
  let updated = today();
  if (fs.existsSync(committedFile)) {
    const committed = fs.readFileSync(committedFile, 'utf8');
    const match = /^updated: (\d{4}-\d{2}-\d{2})$/m.exec(committed);
    if (match && bodyOf(committed) === fresh) updated = match[1];
  }
  return `${frontmatter(front, updated)}\n\n${fresh}`;
}

