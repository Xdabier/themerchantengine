// ── Environment variables ─────────────────────────────────────────────────

export interface EnvVar {
  name: string;
  /** The example value, quotes stripped; empty when the example leaves it blank. */
  example: string;
  /** The comment lines above the assignment, joined. */
  comment: string;
  /** The heading comment the variable sits under, when the file has one. */
  section: string;
  /** True when the example keeps the line commented out (`# NAME=value`). */
  optional: boolean;
}

/** A decorated heading, `# ── Email ────`, or a bare short title, `# Server`: a few words, no sentence punctuation. */
const DECORATED_SECTION = /^#\s*─{2,}\s*(.+?)\s*─*\s*$/;
const SHORT_SECTION = /^#\s+([A-Z][^.:;,]{0,40})$/;
const ASSIGNMENT = /^([A-Z][A-Z0-9_]*)=(.*)$/;
const COMMENTED_ASSIGNMENT = /^#\s*([A-Z][A-Z0-9_]*)=(.*)$/;

/** The heading a comment line states, or null when it is a sentence. */
export function sectionOf(line: string): string | null {
  const decorated = DECORATED_SECTION.exec(line);
  if (decorated) return decorated[1];
  const short = SHORT_SECTION.exec(line);
  if (short && short[1].split(/\s+/).length <= 5) return short[1];
  return null;
}

/** The variables of one example file, in file order, with the comments that explain them. */
export function parseEnvExample(source: string): EnvVar[] {
  const vars: EnvVar[] = [];
  let buffer: string[] = [];
  let section = '';
  // A heading is the first line of a comment block, whether a blank line or
  // the first variable follows it.
  const takeHeading = () => {
    const heading = buffer.length ? sectionOf(buffer[0]) : null;
    if (heading !== null) {
      section = heading;
      buffer.shift();
    }
  };
  for (const raw of source.split(/\r?\n/)) {
    const line = raw.trimEnd();
    if (line.trim() === '') {
      takeHeading();
      buffer = [];
      continue;
    }
    const commented = COMMENTED_ASSIGNMENT.exec(line);
    const assignment = ASSIGNMENT.exec(line);
    if (assignment || commented) {
      takeHeading();
      const [, name, value] = (assignment ?? commented) as RegExpExecArray;
      vars.push({
        name,
        example: value.trim().replace(/^"(.*)"$/, '$1'),
        comment: buffer
          .map((l) => l.replace(/^#\s?/, ''))
          .join(' ')
          .trim(),
        section,
        optional: !assignment,
      });
      buffer = [];
      continue;
    }
    if (line.startsWith('#')) buffer.push(line);
  }
  return vars;
}

// ── Error codes ───────────────────────────────────────────────────────────

export interface ErrorSite {
  file: string;
  line: number;
  exception: string;
  status: number | null;
  message: string | null;
}

export interface ErrorCode {
  code: string;
  statuses: number[];
  sites: ErrorSite[];
}

/** The HTTP status a Nest exception class answers with, or null for a class this process cannot instantiate. */
function statusOf(
  exception: string,
  statusByCustomClass: Map<string, number | null>,
): number | null {
  if (statusByCustomClass.has(exception)) return statusByCustomClass.get(exception) ?? null;
  const Cls = (nestCommon as unknown as Record<string, unknown>)[exception];
  if (typeof Cls !== 'function') return null;
  try {
    const instance = new (Cls as new (message: string) => { getStatus?: () => number })('probe');
    return typeof instance.getStatus === 'function' ? instance.getStatus() : null;
  } catch {
    return null;
  }
}

/** The name of the class a node sits in, or undefined outside a class. */
function findEnclosingClass(node: ts.Node): string | undefined {
  for (let current = node.parent; current; current = current.parent) {
    if (ts.isClassDeclaration(current)) return current.name?.text;
  }
  return undefined;
}

function literalText(node: ts.Node | undefined, source: ts.SourceFile): string | null {
  if (!node) return null;
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text;
  if (ts.isTemplateExpression(node)) return node.getText(source).slice(1, -1);
  return null;
}

/** Every `{ error: { code } }` literal handed to a `new *Exception(...)`, across the given files. */
export function scanErrorCodes(files: string[]): ErrorCode[] {
  const byCode = new Map<string, ErrorCode>();
  // A custom exception class extends a Nest one and may carry `static readonly CODE = '...'`.
  const statusByCustomClass = new Map<string, number | null>();
  const codeByClass = new Map<string, string>();
  const parsed = files.map((file) => ({
    file,
    source: ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true),
  }));
  for (const { source } of parsed) {
    ts.forEachChild(source, function visit(node) {
      if (ts.isClassDeclaration(node) && node.name) {
        const base = node.heritageClauses
          ?.flatMap((clause) => clause.types)
          .map((type) => type.expression.getText(source))
          .find((name) => /Exception$/.test(name));
        if (base) statusByCustomClass.set(node.name.text, statusOf(base, statusByCustomClass));
        for (const member of node.members) {
          if (
            ts.isPropertyDeclaration(member) &&
            member.name.getText(source) === 'CODE' &&
            member.initializer
          ) {
            const initializer = ts.isAsExpression(member.initializer)
              ? member.initializer.expression
              : member.initializer;
            const text = literalText(initializer, source);
            if (text) codeByClass.set(node.name.text, text);
          }
        }
      }
      ts.forEachChild(node, visit);
    });
  }
  for (const { file, source } of parsed) {
    ts.forEachChild(source, function visit(node) {
      // A site is `new XException({...})`, or the `super({...})` call of a class
      // that extends one, where a custom exception carries its own code.
      const isNew = ts.isNewExpression(node) && /Exception$/.test(node.expression.getText(source));
      const isSuper =
        ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.SuperKeyword;
      const enclosingClass = isSuper ? findEnclosingClass(node) : undefined;
      if (isNew || (isSuper && enclosingClass && statusByCustomClass.has(enclosingClass))) {
        const exception = isNew
          ? (node as ts.NewExpression).expression.getText(source)
          : (enclosingClass as string);
        let code: string | null = null;
        let message: string | null = null;
        const find = (inner: ts.Node) => {
          if (ts.isPropertyAssignment(inner)) {
            const name = inner.name.getText(source);
            if (name === 'code' && code === null) {
              code = literalText(inner.initializer, source);
              if (code === null && ts.isPropertyAccessExpression(inner.initializer)) {
                code = codeByClass.get(inner.initializer.expression.getText(source)) ?? null;
              }
            }
            if (name === 'message' && message === null)
              message = literalText(inner.initializer, source);
          }
          ts.forEachChild(inner, find);
        };
        for (const argument of (node as ts.NewExpression | ts.CallExpression).arguments ?? [])
          find(argument);
        if (code) {
          const entry = byCode.get(code) ?? { code, statuses: [], sites: [] };
          const status = statusOf(exception, statusByCustomClass);
          if (status !== null && !entry.statuses.includes(status)) entry.statuses.push(status);
          entry.sites.push({
            file: rel(file),
            line: source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1,
            exception,
            status,
            message,
          });
          byCode.set(code, entry);
        }
      }
      ts.forEachChild(node, visit);
    });
  }
  return [...byCode.values()]
    .map((entry) => ({
      ...entry,
      statuses: [...entry.statuses].sort((a, b) => a - b),
      sites: [...entry.sites].sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line),
    }))
    .sort((a, b) => a.code.localeCompare(b.code));
}

// ── Permissions and the routes that enforce them ──────────────────────────

const HTTP_DECORATORS = new Set(['Get', 'Post', 'Put', 'Patch', 'Delete']);

/** Resolves a decorator argument that is a string literal or an `ADMIN_API_ROUTES.<module>.<key>` reference. */
function routeArgument(node: ts.Expression | undefined, source: ts.SourceFile): string {
  if (!node) return '';
  const literal = literalText(node, source);
  if (literal !== null) return literal;
  const text = node.getText(source);
  const match = /^ADMIN_API_ROUTES\.(\w+)\.(\w+)$/.exec(text);
  if (match) {
    const routes = ADMIN_API_ROUTES as unknown as Record<string, Record<string, string>>;
    const value = routes[match[1]]?.[match[2]];
    if (typeof value === 'string') return value;
  }
  return `<${text}>`;
}

interface Handler {
  source: ts.SourceFile;
  method: ts.MethodDeclaration;
  /** `GET /v1/admin/orders/:id`, the controller prefix and the method path joined, NestJS style. */
  route: string;
  /** The call decorators of the method, the HTTP one included. */
  decorators: ts.CallExpression[];
}

const callDecorators = (node: ts.HasDecorators): ts.CallExpression[] =>
  (ts.getDecorators(node) ?? [])
    .map((d) => d.expression)
    .filter((e): e is ts.CallExpression => ts.isCallExpression(e));

const decoratorNamed = (
  decorators: ts.CallExpression[],
  name: string,
  source: ts.SourceFile,
): ts.CallExpression | undefined => decorators.find((c) => c.expression.getText(source) === name);

/** Visits every route handler (a method under an HTTP decorator) of every controller class in the files. */
function forEachHandler(controllerFiles: string[], visit: (handler: Handler) => void): void {
  for (const file of controllerFiles) {
    const source = ts.createSourceFile(
      file,
      fs.readFileSync(file, 'utf8'),
      ts.ScriptTarget.Latest,
      true,
    );
    ts.forEachChild(source, function walk(node) {
      if (ts.isClassDeclaration(node)) {
        const controller = decoratorNamed(callDecorators(node), 'Controller', source);
        const base = controller ? routeArgument(controller.arguments[0], source) : '';
        for (const member of node.members) {
          if (!ts.isMethodDeclaration(member)) continue;
          const decorators = callDecorators(member);
          const http = decorators.find((c) => HTTP_DECORATORS.has(c.expression.getText(source)));
          if (!http) continue;
          const sub = routeArgument(http.arguments[0], source);
          const route = `${http.expression.getText(source).toUpperCase()} /${[base, sub].filter(Boolean).join('/')}`;
          visit({ source, method: member, route, decorators });
        }
      }
      ts.forEachChild(node, walk);
    });
  }
}

/** `permission -> ["GET /v1/admin/orders", ...]`, read from the `@Permissions` decorators of every controller. */
export function scanEnforcedPermissions(controllerFiles: string[]): Record<string, string[]> {
  const enforced: Record<string, string[]> = {};
  forEachHandler(controllerFiles, ({ source, route, decorators }) => {
    const permissions = decoratorNamed(decorators, 'Permissions', source);
    if (!permissions) return;
    for (const argument of permissions.arguments) {
      const permission = literalText(argument, source);
      if (!permission) continue;
      (enforced[permission] ??= []).push(route);
    }
  });
  for (const key of Object.keys(enforced)) enforced[key] = [...new Set(enforced[key])].sort();
  return Object.fromEntries(Object.entries(enforced).sort(([a], [b]) => a.localeCompare(b)));
}

/**
 * `["POST /v1/orders", ...]`, sorted: every route whose handler takes a
 * parameter decorated `@IdempotencyKey(...)`, written the OpenAPI way
 * (`{id}`, not `:id`) so it matches the routes of the export.
 */
export function scanIdempotentRoutes(controllerFiles: string[]): string[] {
  const routes = new Set<string>();
  forEachHandler(controllerFiles, ({ source, method, route }) => {
    const takesKey = method.parameters.some((parameter) =>
      callDecorators(parameter).some((c) => c.expression.getText(source) === 'IdempotencyKey'),
    );
    if (takesKey) routes.add(route.replace(/:(\w+)/g, '{$1}'));
  });
  return [...routes].sort((a, b) => a.localeCompare(b));
}

// ── CLI flags ─────────────────────────────────────────────────────────────

export interface CliFlag {
  flag: string;
  argument: string | null;
  description: string;
}

/** The flags of the stepper's usage text, one per `  --flag <arg>  description` line. */
export function parseUsage(usage: string): CliFlag[] {
  const flags: CliFlag[] = [];
  for (const line of usage.split('\n')) {
    const match = /^\s+(--[a-z-]+)(?:\s+(<[^>]+>|[a-z.]+\.json))?\s{2,}(.+?)\s*$/.exec(line);
    if (match) flags.push({ flag: match[1], argument: match[2] ?? null, description: match[3] });
  }
  return flags;
}

// ── JSON schema rendering ─────────────────────────────────────────────────

type JsonSchema = Record<string, unknown> & {
  type?: string | string[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  enum?: unknown[];
  $ref?: string;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  allOf?: JsonSchema[];
  description?: string;
  format?: string;
  pattern?: string;
  minimum?: number;
  maximum?: number;
  minLength?: number;
  maxLength?: number;
  nullable?: boolean;
  const?: unknown;
};

const refName = (ref: string): string =>
  ref.replace(/^#\/(?:components\/schemas|\$defs|definitions)\//, '');

/** A one-phrase type for a schema node, with the constraints a reader needs. */
export function schemaType(schema: JsonSchema | undefined): string {
  if (!schema) return 'unknown';
  if (schema.$ref) return `[${refName(schema.$ref)}](#${refName(schema.$ref).toLowerCase()})`;
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map(schemaType).join(' or ');
  if (schema.allOf) return schema.allOf.map(schemaType).join(' and ');
  if (schema.enum) return schema.enum.map((v) => `\`${JSON.stringify(v)}\``).join(', ');
  if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
  const type = Array.isArray(schema.type) ? schema.type.join(' or ') : (schema.type ?? 'unknown');
  if (type === 'array') return `array of ${schemaType(schema.items)}`;
  const constraints: string[] = [];
  if (schema.format) constraints.push(schema.format);
  if (schema.pattern) constraints.push(`pattern \`${schema.pattern}\``);
  if (schema.minimum !== undefined) constraints.push(`min ${schema.minimum}`);
  if (schema.maximum !== undefined) constraints.push(`max ${schema.maximum}`);
  if (schema.minLength !== undefined) constraints.push(`min length ${schema.minLength}`);
  if (schema.maxLength !== undefined) constraints.push(`max length ${schema.maxLength}`);
  if (schema.nullable) constraints.push('nullable');
  return constraints.length ? `${type}, ${constraints.join(', ')}` : type;
}

/** The properties of an object schema as nested bullets, `prefix.name` paths included so a reader can search for one. */
export function renderProperties(schema: JsonSchema | undefined, prefix = '', depth = 0): string[] {
  const lines: string[] = [];
  if (!schema?.properties) return lines;
  const required = new Set(schema.required ?? []);
  for (const [name, property] of Object.entries(schema.properties)) {
    const full = prefix ? `${prefix}.${name}` : name;
    const flags = required.has(name) ? 'required' : 'optional';
    const description = property.description ? ` ${property.description.trim()}` : '';
    const indent = '  '.repeat(depth);
    if (property.properties) {
      lines.push(`${indent}- \`${full}\` (object, ${flags}).${description}`);
      lines.push(...renderProperties(property, full, depth + 1));
    } else if (property.items?.properties) {
      lines.push(`${indent}- \`${full}\` (array of objects, ${flags}).${description} Each item:`);
      lines.push(...renderProperties(property.items, `${full}[]`, depth + 1));
    } else {
      lines.push(`${indent}- \`${full}\` (${schemaType(property)}, ${flags}).${description}`);
    }
  }
  return lines;
}

// ── OpenAPI pages ─────────────────────────────────────────────────────────

interface Operation {
  summary?: string;
  description?: string;
  operationId?: string;
  parameters?: Array<{
    name: string;
    in: string;
    required?: boolean;
    description?: string;
    schema?: JsonSchema;
  }>;
  requestBody?: { required?: boolean; content?: Record<string, { schema?: JsonSchema }> };
  responses?: Record<
    string,
    { description?: string; content?: Record<string, { schema?: JsonSchema }> }
  >;
  security?: unknown[];
}

interface OpenApiDocument {
  paths: Record<string, Record<string, Operation>>;
  components?: { schemas?: Record<string, JsonSchema> };
}

/** The module a path belongs to: the segment after `/v1/` or `/v1/admin/`; the text files the API serves for search engines go under `seo`. */
export function moduleOf(route: string): string {
  if (route === '/health' || route.startsWith('/health/')) return 'health';
  const segment = route.replace(/^\/v1\/(?:admin\/)?/, '').split('/')[0] ?? '';
  if (/\.(?:xml|txt)$/.test(segment)) return 'seo';
  return segment || 'root';
}

const humanize = (slug: string): string =>
  slug.replace(/[-_]+/g, ' ').replace(/^\w/, (c) => c.toUpperCase());

function collectSchemaNames(node: unknown, into: Set<string>): void {
  if (Array.isArray(node)) {
    node.forEach((item) => collectSchemaNames(item, into));
    return;
  }
  if (!node || typeof node !== 'object') return;
  for (const [key, value] of Object.entries(node as Record<string, unknown>)) {
    if (key === '$ref' && typeof value === 'string') into.add(refName(value));
    else collectSchemaNames(value, into);
  }
}

type ModuleOperations = Array<[string, string, Operation]>;

/** The operations of a document grouped by module, modules and routes sorted: the order every page, the HTTP file and the collection share. */
export function operationsByModule(document: OpenApiDocument): Array<[string, ModuleOperations]> {
  const byModule = new Map<string, ModuleOperations>();
  for (const [route, methods] of Object.entries(document.paths)) {
    for (const [method, operation] of Object.entries(methods)) {
      const list = byModule.get(moduleOf(route)) ?? [];
      list.push([method.toUpperCase(), route, operation]);
      byModule.set(moduleOf(route), list);
    }
  }
  return [...byModule.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([module, operations]) => [
      module,
      operations.sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0])),
    ]);
}

/** One page per module of an audience: every operation, then the schemas those operations use. */
export function renderApiPages(
  document: OpenApiDocument,
  audience: 'storefront' | 'admin',
): Map<string, { title: string; body: string; count: number }> {
  const schemas = document.components?.schemas ?? {};
  const pages = new Map<string, { title: string; body: string; count: number }>();
  for (const [module, operations] of operationsByModule(document)) {
    const lines: string[] = [];
    lines.push(
      audience === 'admin'
        ? `Admin routes of the ${humanize(module).toLowerCase()} module. Every route needs a staff session and the permission named on it; send \`X-Resolve-Locale: false\` to receive every locale of a translatable field for editing.`
        : `Storefront and customer routes of the ${humanize(module).toLowerCase()} module. Send \`Accept-Language\` (or \`X-Locale\` from a browser) on every call; a customer route needs the session cookie.`,
    );
    lines.push('');
    for (const [method, route, operation] of operations) {
      lines.push(`## ${method} ${route}`);
      lines.push('');
      lines.push(operation.summary?.trim() || '(no summary)');
      if (operation.description?.trim()) {
        lines.push('');
        lines.push(operation.description.trim());
      }
      const parameters = operation.parameters ?? [];
      if (parameters.length) {
        lines.push('');
        lines.push('Parameters:');
        lines.push('');
        for (const parameter of [...parameters].sort(
          (a, b) => a.in.localeCompare(b.in) || a.name.localeCompare(b.name),
        )) {
          const description = parameter.description ? ` ${parameter.description.trim()}` : '';
          lines.push(
            `- \`${parameter.name}\` in ${parameter.in} (${schemaType(parameter.schema)}, ${parameter.required ? 'required' : 'optional'}).${description}`,
          );
        }
      }
      const body = operation.requestBody?.content?.['application/json']?.schema;
      if (body) {
        lines.push('');
        lines.push(
          `Request body: ${schemaType(body)}${operation.requestBody?.required === false ? ' (optional)' : ''}.`,
        );
        if (body.properties) lines.push('', ...renderProperties(body));
      }
      const responses = Object.entries(operation.responses ?? {}).sort(([a], [b]) =>
        a.localeCompare(b),
      );
      if (responses.length) {
        lines.push('');
        lines.push('Responses:');
        lines.push('');
        for (const [status, response] of responses) {
          const schema = response.content?.['application/json']?.schema;
          const shape = schema ? ` Body: ${schemaType(schema)}.` : '';
          lines.push(
            `- \`${status}\`: ${response.description?.trim() || 'no description'}.${shape}`,
          );
        }
      }
      lines.push('');
    }
    const used = new Set<string>();
    collectSchemaNames(
      operations.map(([, , operation]) => operation),
      used,
    );
    for (let size = -1; size !== used.size; ) {
      size = used.size;
      for (const name of [...used]) collectSchemaNames(schemas[name], used);
    }
    if (used.size) {
      lines.push('## Schemas');
      lines.push('');
      for (const name of [...used].sort()) {
        const schema = schemas[name];
        lines.push(`### ${name}`);
        lines.push('');
        if (schema?.properties) lines.push(...renderProperties(schema));
        else lines.push(schemaType(schema));
        lines.push('');
      }
    }
    pages.set(module, {
      title: humanize(module),
      body: lines.join('\n').trimEnd() + '\n',
      count: operations.length,
    });
  }
  return pages;
}

