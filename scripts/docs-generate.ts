type Components = Record<string, JsonSchema>;

/**
 * A value a request can carry for a schema: a string is the property name or
 * the example, a number 1, a boolean true, an enum its alphabetically first
 * value (so a sample never favours the order a catalogue lists its codes in), an array
 * one item, an object its properties recursed, a `$ref` resolved from the
 * components. A schema with no properties, a cycle or a missing reference
 * gives `{}`, so the body is still valid JSON a reader edits.
 */
export function sampleOf(
  schema: JsonSchema | undefined,
  components: Components,
  name = 'value',
  seen: string[] = [],
): unknown {
  if (!schema) return {};
  if (schema.$ref) {
    const ref = refName(schema.$ref);
    if (seen.includes(ref)) return {};
    return sampleOf(components[ref], components, name, [...seen, ref]);
  }
  if (schema.example !== undefined) return schema.example;
  if (schema.const !== undefined) return schema.const;
  if (schema.enum?.length) {
    return [...schema.enum].sort((a, b) => String(a).localeCompare(String(b)))[0];
  }
  const union = schema.anyOf ?? schema.oneOf;
  if (union?.length) return sampleOf(union[0], components, name, seen);
  if (schema.allOf?.length) {
    return Object.assign(
      {},
      ...schema.allOf.map((part) => sampleOf(part, components, name, seen)),
    ) as unknown;
  }
  const type = Array.isArray(schema.type) ? schema.type[0] : schema.type;
  if (schema.properties || type === 'object') {
    const value: Record<string, unknown> = {};
    for (const [key, property] of Object.entries(schema.properties ?? {}))
      value[key] = sampleOf(property, components, key, seen);
    return value;
  }
  if (type === 'array') return [sampleOf(schema.items, components, name, seen)];
  if (type === 'number' || type === 'integer') return 1;
  if (type === 'boolean') return true;
  return name;
}

const IDEMPOTENCY_HEADER = 'X-Idempotency-Key';
const IDEMPOTENCY_SCHEME = 'idempotency-key';

/**
 * The document's `security` marks an operation first. The export declares the
 * header as a security scheme but no controller applies it to an operation,
 * so the routes `scanIdempotentRoutes` read from the controllers are the
 * fallback.
 */
function takesIdempotencyKey(
  method: string,
  route: string,
  operation: Operation,
  idempotentRoutes: ReadonlySet<string>,
): boolean {
  const marked = (operation.security ?? []).some(
    (entry) => !!entry && typeof entry === 'object' && IDEMPOTENCY_SCHEME in entry,
  );
  return marked || idempotentRoutes.has(`${method} ${route}`);
}

interface SampleRequest {
  summary: string;
  method: string;
  /** The OpenAPI route, `{name}` for a path parameter. */
  route: string;
  /** Required query parameters with their sample values. */
  query: Array<{ key: string; value: string }>;
  headers: Array<{ key: string; value: string }>;
  /** The JSON sample, already serialized; undefined without a JSON request body. */
  body?: string;
}

const BODY_JSON = (value: unknown): string => JSON.stringify(value, null, 2);

/**
 * Better Auth's routes are mounted as a raw handler and are absent from the
 * export; these four are what a storefront needs. Sign-up carries `firstName`
 * and `lastName` because `apps/api/src/auth/auth.ts` declares them as required
 * additional fields (the user's `name` is derived from them).
 */
const headersFor = (hasBody: boolean, idempotent = false): SampleRequest['headers'] => [
  { key: 'Accept-Language', value: '{{locale}}' },
  ...(hasBody ? [{ key: 'Content-Type', value: 'application/json' }] : []),
  ...(idempotent ? [{ key: IDEMPOTENCY_HEADER, value: '{{$guid}}' }] : []),
];

