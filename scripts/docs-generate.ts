/** Every request of a document in page order, the audience-independent headers and the sample body filled in. */
function sampleRequests(
  document: OpenApiDocument,
  idempotentRoutes: Iterable<string> = [],
): Array<[string, SampleRequest[]]> {
  const components = document.components?.schemas ?? {};
  const idempotent = new Set(idempotentRoutes);
  return operationsByModule(document).map(([module, operations]) => [
    module,
    operations.map(([method, route, operation]) => {
      const schema = operation.requestBody?.content?.['application/json']?.schema;
      const headers = headersFor(
        !!schema,
        takesIdempotencyKey(method, route, operation, idempotent),
      );
      const query = (operation.parameters ?? [])
        .filter((parameter) => parameter.in === 'query' && parameter.required)
        .map((parameter) => ({
          key: parameter.name,
          value: String(sampleOf(parameter.schema, components, parameter.name)),
        }));
      return {
        summary: operation.summary?.trim() || `${method} ${route}`,
        method,
        route,
        query,
        headers,
        body: schema ? BODY_JSON(sampleOf(schema, components)) : undefined,
      };
    }),
  ]);
}

const queryString = (query: SampleRequest['query']): string =>
  query.length
    ? `?${query.map(({ key, value }) => `${key}=${encodeURIComponent(value)}`).join('&')}`
    : '';

const PATH_PARAMETER = /\{(\w+)\}/g;

/** Every distinct `{name}` of the routes, sorted, so the file declares each one as a variable. */
const pathParameters = (samples: Array<[string, SampleRequest[]]>): string[] => {
  const names = new Set<string>();
  for (const [, requests] of samples)
    for (const sample of requests)
      for (const match of sample.route.matchAll(PATH_PARAMETER)) names.add(match[1]);
  return [...names].sort((a, b) => a.localeCompare(b));
};

/**
 * The storefront document as a REST Client / IntelliJ `.http` file: the
 * variables, the auth block, then one request per operation in page order.
 * `idempotentRoutes` is what `scanIdempotentRoutes` found in the controllers.
 */
export function renderHttpFile(
  document: OpenApiDocument,
  idempotentRoutes: Iterable<string> = [],
): string {
  const samples = sampleRequests(document, idempotentRoutes);
  const lines: string[] = [];
  lines.push(
    `# ${PAGE_MARKER.replace(/^<!-- /, '').replace(/ -->$/, '')}`,
    '# Every storefront operation of the OpenAPI document, one request each, in the order of the reference pages. Open it with the REST Client extension of VS Code or with IntelliJ; the cookie jar keeps the session after Sign in.',
    '@baseUrl = https://api.shop.example/api',
    '@locale = en',
    // A path parameter is a file variable; each one is declared here so the request runs as written.
    ...pathParameters(samples).map((name) => `@${name} = ${name}`),
    '',
    `# ${AUTH_NOTE}`,
    '',
  );
  const request = (sample: SampleRequest) => {
    lines.push(`### ${sample.summary}`);
    lines.push(
      `${sample.method} {{baseUrl}}${sample.route.replace(PATH_PARAMETER, '{{$1}}')}${queryString(sample.query)}`,
    );
    for (const header of sample.headers) lines.push(`${header.key}: ${header.value}`);
    lines.push('');
    if (sample.body !== undefined) lines.push(sample.body, '');
  };
  for (const sample of AUTH_REQUESTS) request(sample);
  for (const [module, requests] of samples) {
    lines.push(`# Module: ${module}`, '');
    for (const sample of requests) request(sample);
  }
  return lines.join('\n').trimEnd() + '\n';
}

export interface PostmanRequestItem {
  name: string;
  request: {
    method: string;
    header: Array<{ key: string; value: string }>;
    url: {
      raw: string;
      host: string[];
      path: string[];
      variable?: Array<{ key: string; value: string }>;
      query?: Array<{ key: string; value: string }>;
    };
    body?: { mode: 'raw'; raw: string; options: { raw: { language: 'json' } } };
  };
}

export interface PostmanFolder {
  name: string;
  description?: string;
  item: PostmanRequestItem[];
}

export interface PostmanCollection {
  info: { name: string; description: string; schema: string };
  item: Array<{ name: string; description: string; item: PostmanFolder[] }>;
}

function postmanItem(sample: SampleRequest): PostmanRequestItem {
  const route = sample.route.replace(/\{(\w+)\}/g, ':$1');
  const variables = [...sample.route.matchAll(/\{(\w+)\}/g)].map((match) => ({
    key: match[1],
    value: '',
  }));
  const url: PostmanRequestItem['request']['url'] = {
    raw: `{{baseUrl}}${route}${queryString(sample.query)}`,
    host: ['{{baseUrl}}'],
    path: route.split('/').filter(Boolean),
  };
  if (variables.length) url.variable = variables;
  if (sample.query.length) url.query = sample.query;
  const item: PostmanRequestItem = {
    name: sample.summary,
    request: { method: sample.method, header: [...sample.headers], url },
  };
  if (sample.body !== undefined) {
    item.request.body = {
      mode: 'raw',
      raw: sample.body,
      options: { raw: { language: 'json' } },
    };
  }
  return item;
}

