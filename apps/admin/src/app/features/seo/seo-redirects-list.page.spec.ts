import { Dialog } from '@angular/cdk/dialog';
import { ComponentFixture, TestBed } from '@angular/core/testing';
import { ActivatedRoute, Router, provideRouter } from '@angular/router';
import { ApiForbiddenError, ApiServerError } from '@admin-types';
import { SeoService } from '@admin-services';
import { axe, toHaveNoViolations } from 'jest-axe';
import { BehaviorSubject, of, throwError } from 'rxjs';
import { BOOTSTRAP_LOCALE } from '../../core/tokens';
import { AuthStore } from '../../core/stores/auth.store';
import { SeoRedirectsListPage } from './seo-redirects-list.page';
import { provideStoreSettingsStub } from '../../../testing/store-settings.mock';

expect.extend(toHaveNoViolations);

const sample = {
  id: 'redir-1',
  fromPath: '/old',
  toPath: '/new',
  type: 'MOVED_PERMANENTLY' as const,
  isAutoGenerated: false,
  createdAt: '2026-04-15T00:00:00.000Z',
};
const listFixture = {
  data: [sample],
  meta: { page: 1, pageSize: 20, total: 1 },
};

describe('SeoRedirectsListPage', () => {
  let fixture: ComponentFixture<SeoRedirectsListPage>;
  let page: SeoRedirectsListPage;
  let listSpy: jest.Mock;
  let deleteSpy: jest.Mock;
  let queryParams$: BehaviorSubject<Record<string, string>>;
  let dialogOpenResult: boolean;
  let permissions: Set<string>;

  function configure(params: Record<string, string> = {}) {
    queryParams$ = new BehaviorSubject<Record<string, string>>(params);
    dialogOpenResult = true;
    TestBed.configureTestingModule({
      providers: [
        provideStoreSettingsStub(),
        provideRouter([{ path: '**', children: [] }]),
        { provide: BOOTSTRAP_LOCALE, useValue: 'fr' },
        {
          provide: SeoService,
          useValue: { listRedirects: listSpy, deleteRedirect: deleteSpy },
        },
        {
          provide: AuthStore,
          useValue: {
            locale: () => 'fr',
            hasPermission: (p: string) => permissions.has(p),
          },
        },
        {
          provide: ActivatedRoute,
          useValue: { queryParams: queryParams$.asObservable() },
        },
        {
          provide: Dialog,
          useValue: {
            open: jest.fn(() => ({
              closed: of(dialogOpenResult),
            })),
          },
        },
      ],
    });
    fixture = TestBed.createComponent(SeoRedirectsListPage);
    page = fixture.componentInstance;
    fixture.detectChanges();
  }

  beforeEach(() => {
    permissions = new Set(['seo:view', 'seo:create', 'seo:delete']);
    listSpy = jest.fn(() => of(listFixture));
    deleteSpy = jest.fn(() => of(undefined));
  });

  it('fetches with defaults when URL has no filters', () => {
    configure();
    expect(listSpy).toHaveBeenCalledWith({
      page: 1,
      pageSize: 20,
      sortBy: 'createdAt',
      sortOrder: 'desc',
    });
    expect(page.total()).toBe(1);
  });

  it('forwards isAutoGenerated=true when URL says AUTO', () => {
    configure({ isAutoGenerated: 'true' });
    expect(listSpy).toHaveBeenCalledWith(expect.objectContaining({ isAutoGenerated: true }));
  });

  it('forwards isAutoGenerated=false when URL says MANUAL', () => {
    configure({ isAutoGenerated: 'false' });
    expect(listSpy).toHaveBeenCalledWith(expect.objectContaining({ isAutoGenerated: false }));
  });

  it('forwards search param when URL carries it', () => {
    configure({ search: '/old' });
    expect(listSpy).toHaveBeenCalledWith(expect.objectContaining({ search: '/old' }));
  });

  it('setAutoFilter navigates with the right param', async () => {
    configure();
    const router = TestBed.inject(Router);
    const spy = jest.spyOn(router, 'navigate').mockResolvedValue(true);
    page.setAutoFilter('AUTO');
    expect(spy).toHaveBeenCalledWith(
      [],
      expect.objectContaining({
        queryParams: expect.objectContaining({ isAutoGenerated: 'true' }),
      }),
    );
    page.setAutoFilter('ALL');
    expect(spy).toHaveBeenLastCalledWith(
      [],
      expect.objectContaining({
        queryParams: expect.objectContaining({ isAutoGenerated: null }),
      }),
    );
  });

  it('goToPage navigates to the target page within bounds', () => {
    listSpy = jest.fn(() => of({ data: [sample], meta: { page: 1, pageSize: 20, total: 100 } }));
    configure({ page: '2' });
    const router = TestBed.inject(Router);
    const spy = jest.spyOn(router, 'navigate').mockResolvedValue(true);
    page.goToPage(3);
    expect(spy).toHaveBeenCalledWith([], expect.objectContaining({ queryParams: { page: 3 } }));
  });

  it('goToPage refuses invalid page numbers', () => {
    configure();
    const router = TestBed.inject(Router);
    const spy = jest.spyOn(router, 'navigate').mockResolvedValue(true);
    page.goToPage(0);
    page.goToPage(999);
    expect(spy).not.toHaveBeenCalled();
  });

  it('confirmDelete calls deleteRedirect and refetches on confirm', async () => {
    configure();
    listSpy.mockClear();
    await page.confirmDelete(sample);
    expect(deleteSpy).toHaveBeenCalledWith('redir-1');
    expect(listSpy).toHaveBeenCalled();
  });

  it('confirmDelete does nothing when the user cancels', async () => {
    configure();
    dialogOpenResult = false;
    await page.confirmDelete(sample);
    expect(deleteSpy).not.toHaveBeenCalled();
  });

  it('surfaces delete errors without throwing', async () => {
    configure();
    deleteSpy.mockReturnValue(
      throwError(() => new ApiServerError({ code: 'SERVER', message: 'boom', status: 500 })),
    );
    await page.confirmDelete(sample);
    expect(page.error()).toBeTruthy();
  });

  it('hides the create CTA when user lacks seo:create', () => {
    permissions = new Set(['seo:view']);
    configure();
    const el = fixture.nativeElement as HTMLElement;
    expect(el.querySelector('[data-testid="seo-redirects-new-cta"]')).toBeNull();
  });

  it('hides the delete action when user lacks seo:delete', () => {
    permissions = new Set(['seo:view']);
    configure();
    const el = fixture.nativeElement as HTMLElement;
    expect(el.querySelector('[data-testid^="seo-redirect-delete-"]')).toBeNull();
  });

  it('surfaces user-safe 403 copy when the list errors', () => {
    listSpy = jest.fn(() =>
      throwError(() => new ApiForbiddenError({ code: 'FORBIDDEN', message: 'nope' })),
    );
    configure();
    expect(page.error()).toMatch(/permission/i);
  });

  it('search input is wired to the search form control', () => {
    configure({ search: '/initial' });
    expect(page.searchControl.value).toBe('/initial');
  });

  it('is axe-clean', async () => {
    configure();
    const results = await axe(fixture.nativeElement as Element);
    expect(results).toHaveNoViolations();
  });
});
