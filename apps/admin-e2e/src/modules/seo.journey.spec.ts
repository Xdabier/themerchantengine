test('/seo/redirects/new creates and redirects back to the list', async ({ page, baseURL }) => {
  const fromPath = uniquePath('create');
  await page.goto('/seo/redirects/new', { waitUntil: 'networkidle' });

  await page.locator('[data-testid="seo-redirect-from"]').locator('input').fill(fromPath);
  await page
    .locator('[data-testid="seo-redirect-to"]')
    .locator('input')
    .fill('/e2e-created-target');

  await page.locator('[data-testid="seo-redirect-submit"]').locator('button').click();
  await page.waitForURL(/\/seo\/redirects($|\?)/);
  await expect(page.locator('[data-testid="seo-redirects-list-page"]')).toBeVisible({
    timeout: 10_000,
  });

  const search = page.locator('[data-testid="seo-search"]');
  await search.fill(fromPath);
  // Debounce + refetch.
  await page.waitForTimeout(400);
  await expect(page.getByText(fromPath).first()).toBeVisible({ timeout: 10_000 });

  // Cleanup via API — find the id through the list endpoint.
  const cookies = getAdminCookies(baseURL!);
  const ctx = await request.newContext({ baseURL });
  const listRes = await ctx.get(
    `/api/v1/admin/seo/redirects?search=${encodeURIComponent(fromPath)}`,
    { headers: { Cookie: cookies } },
  );
  const { data } = (await listRes.json()) as { data: Array<{ id: string; fromPath: string }> };
  await ctx.dispose();
  const row = data.find((r) => r.fromPath === fromPath);
  if (row) await deleteRedirectViaApi(baseURL!, row.id);
});

