test('/seo/indexing Resubmit sitemap confirms → POST /seo/submit → result announced', async ({
  page,
}) => {
  await page.goto('/seo/indexing', { waitUntil: 'networkidle' });
  await page.locator('[data-testid="seo-indexing-resubmit-sitemap"]').click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible({ timeout: 10_000 });

  // The dialog fires a dryRun POST in ngOnInit before the confirm button is
  // enabled (previewing = true → disabled).  Wait for the preview text to
  // clear ("Checking…" disappears) so that:
  //   a) the dryRun POST has already completed — waitForResponse below won't
  //      capture it by mistake;
  //   b) the inner <button> is genuinely enabled when we click it.
  await expect(dialog.getByTestId('seo-submit-preview')).not.toContainText(/checking/i, {
    timeout: 10_000,
  });

  const submitResponse = page.waitForResponse(
    (res) => res.url().includes('/v1/admin/seo/submit') && res.request().method() === 'POST',
  );
  // Click the inner <button> (not the app-button host) — Playwright's
  // actionability check waits for disabled to clear on the native element.
  // This is the same pattern used throughout the spec (lines 92, 123, 172).
  await dialog.getByTestId('seo-submit-confirm').locator('button').click();
  const res = await submitResponse;
  expect(res.status()).toBe(200);

  // The result line populates (success or per-engine outcome — env-independent).
  await expect(page.locator('[data-testid="seo-submit-result"]')).not.toHaveText(/^\s*$/, {
    timeout: 10_000,
  });
});
