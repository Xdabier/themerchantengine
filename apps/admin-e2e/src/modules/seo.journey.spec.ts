/**
 * R5.2 — SEO admin journey.
 *
 * Covers `/seo/redirects` (list + delete + filter + search round-trip),
 * `/seo/redirects/new` (create + leading-slash validator + 409 conflict
 * mapping), and `/seo/health` (three sections render). Live backend. No
 * `page.route()`, no fixtures.
 *
 * Determinism: every write test seeds its own `/e2e-seo-<timestamp>` row via
 * the admin API so concurrent browsers never collide on `fromPath`.
 */

function uniquePath(label: string): string {
  return `/e2e-seo-${label}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

async function seedRedirect(
  baseURL: string,
  fromPath: string,
  toPath: string,
): Promise<{ id: string; fromPath: string; toPath: string }> {
  const cookies = getAdminCookies(baseURL);
  const ctx = await request.newContext({ baseURL });
  const res = await ctx.post('/api/v1/admin/seo/redirects', {
    headers: { Cookie: cookies },
    data: { fromPath, toPath, type: 'MOVED_PERMANENTLY' },
  });
  const raw = await res.text();
  await ctx.dispose();
  if (!res.ok()) {
    throw new Error(`[seo.journey] seed redirect failed: ${res.status()} ${raw.slice(0, 200)}`);
  }
  const { data } = JSON.parse(raw) as {
    data: { id: string; fromPath: string; toPath: string };
  };
  return data;
}

async function deleteRedirectViaApi(baseURL: string, id: string): Promise<void> {
  const cookies = getAdminCookies(baseURL);
  const ctx = await request.newContext({ baseURL });
  await ctx.delete(`/api/v1/admin/seo/redirects/${id}`, {
    headers: { Cookie: cookies },
  });
  await ctx.dispose();
}

