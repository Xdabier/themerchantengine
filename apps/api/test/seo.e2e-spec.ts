import { PrismaClient, RedirectType } from '@prisma/client';
import { api, createTestPrisma, signUpCustomer, loginAs, ADMIN } from '../../../test/e2e/helpers';

// ── Constants ─────────────────────────────────────────────────────────────────

const TEST_SUFFIX = '@e2e-seo.test';
const TEST_PASSWORD = 'StrongPass1!';

// ── Suite ─────────────────────────────────────────────────────────────────────

describe('SEO (e2e)', () => {
  let prisma: PrismaClient;

  let adminCookie: string;
  let customerCookie: string;

  // ── Setup ──────────────────────────────────────────────────────────────────

  beforeAll(async () => {
    prisma = createTestPrisma();

    // SUPER_ADMIN (seeded) bypasses all permission checks (PermissionsGuard §3.3).
    adminCookie = await loginAs(ADMIN.email, ADMIN.password);

    // ── Customer user ──
    customerCookie = await signUpCustomer(prisma, `customer${TEST_SUFFIX}`, TEST_PASSWORD, {
      firstName: 'Seo',
      lastName: 'Customer',
    });
  });

  afterAll(async () => {
    await prisma.seoRedirect.deleteMany({ where: { fromPath: { contains: 'e2e-seo' } } });
    await prisma.seoSubmission.deleteMany({ where: { targetRef: { contains: 'e2e-seo' } } });
    await prisma.user.deleteMany({ where: { email: { contains: TEST_SUFFIX } } });
    await prisma.$disconnect();
  });

  // ── Storefront public endpoints ────────────────────────────────────────────

  describe('GET /v1/sitemap_index.xml', () => {
    it('returns 200 with XML content-type without authentication', async () => {
      const res = await api().get('/v1/sitemap_index.xml');

      expect(res.status).toBe(200);
      expect(res.headers['content-type']).toMatch(/xml/);
      expect(res.text).toContain('<?xml');
      expect(res.text).toContain('sitemapindex');
    });
  });

  describe('GET /v1/sitemap.xml', () => {
    it('redirects to sitemap_index.xml', async () => {
      const res = await api().get('/v1/sitemap.xml').redirects(0);

      expect(res.status).toBe(301);
      expect(res.headers['location']).toContain('sitemap_index.xml');
    });
  });

  describe('GET /v1/sitemap-products.xml', () => {
    it('returns XML with urlset', async () => {
      const res = await api().get('/v1/sitemap-products.xml');

      expect(res.status).toBe(200);
      expect(res.text).toContain('<urlset');
    });
  });

  describe('GET /v1/robots.txt', () => {
    it('returns robots.txt without authentication', async () => {
      const res = await api().get('/v1/robots.txt');

      expect(res.status).toBe(200);
      expect(res.headers['content-type']).toMatch(/text\/plain/);
      expect(res.text).toContain('User-agent: *');
      expect(res.text).toContain('Sitemap:');
    });

    it('disallows admin paths', async () => {
      const res = await api().get('/v1/robots.txt');

      expect(res.text).toContain('Disallow: /v1/admin/');
    });

    it('includes AI crawler disallow rules', async () => {
      const res = await api().get('/v1/robots.txt');

      expect(res.text).toContain('GPTBot');
    });
  });

  // ── Admin: Redirects ───────────────────────────────────────────────────────

  describe('POST /v1/admin/seo/redirects', () => {
    it('creates a redirect with seo:create permission', async () => {
      const res = await api()
        .post('/v1/admin/seo/redirects')
        .set('Cookie', adminCookie)
        .send({ fromPath: '/e2e-seo-old', toPath: '/e2e-seo-new' });

      expect(res.status).toBe(201);
      expect(res.body.data).toMatchObject({
        fromPath: '/e2e-seo-old',
        toPath: '/e2e-seo-new',
        type: RedirectType.MOVED_PERMANENTLY,
        isAutoGenerated: false,
      });
    });

    it('returns 409 when fromPath already exists', async () => {
      const res = await api()
        .post('/v1/admin/seo/redirects')
        .set('Cookie', adminCookie)
        .send({ fromPath: '/e2e-seo-old', toPath: '/different-target' });

      expect(res.status).toBe(409);
    });

    it('returns 400 when fromPath does not start with /', async () => {
      const res = await api()
        .post('/v1/admin/seo/redirects')
        .set('Cookie', adminCookie)
        .send({ fromPath: 'no-slash', toPath: '/target' });

      expect(res.status).toBe(400);
    });

    it('returns 403 for customer without seo:create', async () => {
      const res = await api()
        .post('/v1/admin/seo/redirects')
        .set('Cookie', customerCookie)
        .send({ fromPath: '/e2e-forbidden', toPath: '/target' });

      expect(res.status).toBe(403);
    });
  });

  describe('GET /v1/admin/seo/redirects', () => {
    it('lists redirects for admin', async () => {
      const res = await api()
        .get('/v1/admin/seo/redirects')
        .set('Cookie', adminCookie);

      expect(res.status).toBe(200);
      expect(res.body.data).toBeInstanceOf(Array);
      expect(res.body.meta).toMatchObject({ page: 1 });
    });

    it('filters by isAutoGenerated=false', async () => {
      const res = await api()
        .get('/v1/admin/seo/redirects?isAutoGenerated=false')
        .set('Cookie', adminCookie);

      expect(res.status).toBe(200);
      const items = res.body.data as { isAutoGenerated: boolean }[];
      expect(items.every((r) => r.isAutoGenerated === false)).toBe(true);
    });

    it('returns 401 without authentication', async () => {
      const res = await api().get('/v1/admin/seo/redirects');
      expect(res.status).toBe(401);
    });
  });

  describe('DELETE /v1/admin/seo/redirects/:id', () => {
    it('deletes a redirect', async () => {
      // Create a redirect to delete
      const create = await api()
        .post('/v1/admin/seo/redirects')
        .set('Cookie', adminCookie)
        .send({ fromPath: '/e2e-seo-to-delete', toPath: '/target' });

      const id = create.body.data.id as string;

      const del = await api()
        .delete(`/v1/admin/seo/redirects/${id}`)
        .set('Cookie', adminCookie);

      expect(del.status).toBe(204);
    });

    it('returns 404 for unknown redirect id', async () => {
      const res = await api()
        .delete('/v1/admin/seo/redirects/non-existent-id')
        .set('Cookie', adminCookie);

      expect(res.status).toBe(404);
    });
  });

  // ── Admin: Health check ────────────────────────────────────────────────────

  describe('GET /v1/admin/seo/health', () => {
    it('returns health report structure', async () => {
      const res = await api()
        .get('/v1/admin/seo/health')
        .set('Cookie', adminCookie);

      expect(res.status).toBe(200);
      expect(res.body.data).toHaveProperty('productsMissingMeta');
      expect(res.body.data).toHaveProperty('productsMissingAlt');
      expect(res.body.data).toHaveProperty('pagesMissingMeta');
      expect(res.body.data.productsMissingMeta).toHaveProperty('count');
      expect(res.body.data.productsMissingMeta).toHaveProperty('items');
    });

    it('returns 403 for customer', async () => {
      const res = await api()
        .get('/v1/admin/seo/health')
        .set('Cookie', customerCookie);

      expect(res.status).toBe(403);
    });
  });

  // ── Admin: Submission audit log (DR-17) ────────────────────────────────────

  describe('GET /v1/admin/seo/submissions', () => {
    beforeAll(async () => {
      await prisma.seoSubmission.createMany({
        data: [
          {
            trigger: 'manual',
            targetType: 'url',
            targetRef: 'e2e-seo:product:widget',
            engine: 'indexnow',
            requestedCount: 2,
            submittedCount: 2,
            accepted: true,
          },
          {
            trigger: 'cron',
            targetType: 'sitemap',
            targetRef: 'e2e-seo:sitemap',
            engine: 'gsc',
            requestedCount: 1,
            submittedCount: 1,
            accepted: true,
          },
          {
            trigger: 'cron',
            targetType: 'sitemap',
            targetRef: 'e2e-seo:sitemap',
            engine: 'bing',
            requestedCount: 1,
            submittedCount: 0,
            accepted: false,
            reason: 'disabled',
          },
        ],
      });
    });

    it('lists submissions for admin with data + meta', async () => {
      const res = await api().get('/v1/admin/seo/submissions').set('Cookie', adminCookie);

      expect(res.status).toBe(200);
      expect(res.body.data).toBeInstanceOf(Array);
      expect(res.body.meta).toMatchObject({ page: 1 });
      const ours = (res.body.data as { targetRef: string }[]).filter((r) =>
        r.targetRef.includes('e2e-seo'),
      );
      expect(ours.length).toBeGreaterThanOrEqual(1);
    });

    it('filters by engine', async () => {
      const res = await api()
        .get('/v1/admin/seo/submissions?engine=gsc')
        .set('Cookie', adminCookie);

      expect(res.status).toBe(200);
      const items = res.body.data as { engine: string }[];
      expect(items.every((r) => r.engine === 'gsc')).toBe(true);
    });

    it('filters by accepted=false', async () => {
      const res = await api()
        .get('/v1/admin/seo/submissions?accepted=false')
        .set('Cookie', adminCookie);

      expect(res.status).toBe(200);
      const items = res.body.data as { accepted: boolean }[];
      expect(items.every((r) => r.accepted === false)).toBe(true);
    });

    it('returns 400 for an out-of-allowlist sortBy', async () => {
      const res = await api()
        .get('/v1/admin/seo/submissions?sortBy=reason')
        .set('Cookie', adminCookie);

      expect(res.status).toBe(400);
    });

    it('returns 401 without authentication', async () => {
      const res = await api().get('/v1/admin/seo/submissions');
      expect(res.status).toBe(401);
    });

    it('returns 403 for customer without seo:view', async () => {
      const res = await api()
        .get('/v1/admin/seo/submissions')
        .set('Cookie', customerCookie);

      expect(res.status).toBe(403);
    });
  });

  // ── Redirect middleware ────────────────────────────────────────────────────

  describe('SeoRedirectMiddleware', () => {
    const fromPath = '/e2e-seo-middleware-old';
    const toPath = '/e2e-seo-middleware-new';
    let redirectId: string;

    beforeAll(async () => {
      const res = await api()
        .post('/v1/admin/seo/redirects')
        .set('Cookie', adminCookie)
        .send({ fromPath, toPath });
      redirectId = res.body.data?.id as string;
    });

    afterAll(async () => {
      if (redirectId) {
        await prisma.seoRedirect.delete({ where: { id: redirectId } }).catch(() => {});
      }
    });

    it('issues a 301 when a registered redirect path is requested', async () => {
      const res = await api().get(fromPath).redirects(0);

      expect(res.status).toBe(301);
      expect(res.headers['location']).toBe(toPath);
    });

    it('passes through for paths with no registered redirect', async () => {
      const res = await api().get('/no-redirect-here').redirects(0);

      // Should not be a 301 from redirect middleware (could be 404 from app router)
      expect(res.status).not.toBe(301);
    });
  });
});
