import { IsBoolean, IsIn, IsInt, IsOptional, IsString, Max, Min } from 'class-validator';
import { Transform, Type } from 'class-transformer';
import {
  SEO_REDIRECTS_DEFAULT_PAGE_SIZE,
  SEO_REDIRECTS_MAX_PAGE_SIZE,
  VALID_REDIRECT_SORT_FIELDS,
} from '../seo.constants';

export class ListRedirectsAdminDto {
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  page?: number;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(SEO_REDIRECTS_MAX_PAGE_SIZE)
  pageSize?: number = SEO_REDIRECTS_DEFAULT_PAGE_SIZE;

  @IsOptional()
  @IsIn(VALID_REDIRECT_SORT_FIELDS)
  sortBy?: (typeof VALID_REDIRECT_SORT_FIELDS)[number];

  @IsOptional()
  @IsIn(['asc', 'desc'])
  sortOrder?: 'asc' | 'desc';

  /** Filter by whether the redirect was auto-generated from a slug change. */
  @IsOptional()
  @Transform(({ value }) => {
    if (value === 'true') return true;
    if (value === 'false') return false;
    return value;
  })
  @IsBoolean()
  isAutoGenerated?: boolean;

  /** Filter by fromPath substring. */
  @IsOptional()
  @IsString()
  search?: string;
}
