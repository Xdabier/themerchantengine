import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  Post,
  Query,
  Req,
} from '@nestjs/common';
import { ApiOperation, ApiTags } from '@nestjs/swagger';
import { Permissions, RateLimit } from '@common/decorators';
import { ADMIN_API_ROUTES } from '@admin-routes';
import {
  IdempotencyKey,
  IdempotencyKeyPipe,
} from '../../common/decorators/idempotency-key.decorator';
import { SeoService } from './seo.service';
import { SeoSubmissionService } from './seo-submission.service';
import { SeoSubmitOrchestrator } from './seo-submit.orchestrator';
import { SeoInsightsService } from './seo-insights.service';
import {
  CreateRedirectAdminDto,
  GetSeoAnalyticsAdminDto,
  InspectUrlAdminDto,
  ListRedirectsAdminDto,
  ListSeoSubmissionsAdminDto,
  SubmitSeoAdminDto,
} from './dto';

// ── Admin ─────────────────────────────────────────────────────────────────────

@ApiTags('seo')
@Controller(ADMIN_API_ROUTES.seo.base)
export class SeoAdminController {
  constructor(
    private readonly service: SeoService,
    private readonly submissions: SeoSubmissionService,
    private readonly submitOrchestrator: SeoSubmitOrchestrator,
    private readonly insights: SeoInsightsService,
  ) {}

  /**
   * List SEO redirects with optional filters.
   * Supports isAutoGenerated boolean filter and fromPath search.
   */
  @Get(ADMIN_API_ROUTES.seo.redirects)
  @Permissions('seo:view')
  @RateLimit.Admin()
  @ApiOperation({ summary: 'List SEO redirects' })
  listRedirects(@Query() dto: ListRedirectsAdminDto) {
    return this.service.listRedirects(dto);
  }

  /**
   * Manually create a 301/302 redirect.
   * Rejects with 409 if fromPath already exists.
   */
  @Post(ADMIN_API_ROUTES.seo.redirects)
  @Permissions('seo:create')
  @RateLimit.Admin()
  @ApiOperation({ summary: 'Create new SEO redirect' })
  createRedirect(@Body() dto: CreateRedirectAdminDto) {
    return this.service.createRedirect(dto);
  }

  /**
   * Delete a redirect by ID.
   */
  @Delete(ADMIN_API_ROUTES.seo.redirectById)
  @Permissions('seo:delete')
  @RateLimit.Admin()
  @HttpCode(HttpStatus.NO_CONTENT)
  @ApiOperation({ summary: 'Delete SEO redirect' })
  async deleteRedirect(@Param('id') id: string): Promise<void> {
    await this.service.deleteRedirect(id);
  }

  /**
   * SEO health check report.
   * Returns products missing meta tags, images missing alt text,
   * and published pages without meta descriptions.
   */
  @Get(ADMIN_API_ROUTES.seo.health)
  @Permissions('seo:view')
  @RateLimit.Admin()
  @ApiOperation({ summary: 'Get SEO health check report' })
  getHealth() {
    return this.service.getHealth();
  }

  /**
   * Paginated search-engine submission audit history (DR-17). Filterable by
   * engine / trigger / targetType / accepted / date range; sorted by createdAt.
   * The durable record that makes silent fail-open submissions visible.
   */
  @Get(ADMIN_API_ROUTES.seo.submissions)
  @Permissions('seo:view')
  @RateLimit.Admin()
  @ApiOperation({ summary: 'List search engine submission history' })
  listSubmissions(@Query() dto: ListSeoSubmissionsAdminDto) {
    return this.submissions.list(dto);
  }

  /**
   * Manual reindex (DR-17 D2). Pushes one URL / many products to IndexNow, or
   * resubmits the whole sitemap to GSC + Bing, recording a durable audit row
   * per engine. Idempotent (`X-Idempotency-Key`) so a double-click never
   * double-burns crawler quota; `seo:manage` + a dedicated tight rate-limit
   * because every accepted call spends finite quota. `dryRun` previews the URL
   * count + dedup-skip estimate without spending. Returns 200 (action, not a
   * REST resource creation) for both a fresh submit and an idempotent replay.
   */
  @Post(ADMIN_API_ROUTES.seo.submit)
  @Permissions('seo:manage')
  @RateLimit.SeoSubmit()
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: 'Submit URLs or sitemap to search engines for reindexing' })
  submitSeo(
    @Body() dto: SubmitSeoAdminDto,
    @Req() req: { id: string; user: { id: string } },
    @IdempotencyKey(IdempotencyKeyPipe) idempotencyKey: string,
  ) {
    return this.submitOrchestrator.submitManual(dto, req.user.id, idempotencyKey, req.id ?? null);
  }

  /**
   * Per-engine sitemap coverage (DR-17 D3) — GSC `sitemaps.list` (`contents[].submitted`)
   * + Bing `GetFeeds`. Read-only, Redis-cached 6 h; degrades per engine (a disabled
   * engine reports `state:'disabled'`, never an error). No-store (global default).
   */
  @Get(ADMIN_API_ROUTES.seo.coverage)
  @Permissions('seo:view')
  @RateLimit.Admin()
  @ApiOperation({ summary: 'Get per-engine sitemap coverage' })
  getCoverage() {
    return this.insights.getSitemapCoverage();
  }

  /**
   * Quota readout (DR-17 D3) — live Bing URL-submission quota (cached 15–60 min),
   * the GSC URL-Inspection daily-budget estimate, and the IndexNow dedup window.
   * Read-only; degrades per engine.
   */
  @Get(ADMIN_API_ROUTES.seo.quota)
  @Permissions('seo:view')
  @RateLimit.Admin()
  @ApiOperation({ summary: 'Get search engine submission quota readout' })
  getQuota() {
    return this.insights.getQuota();
  }

  /**
   * GSC Search Analytics rollup (DR-17 D4) — totals + a daily series + the top
   * queries and pages over the requested lookback window (`?range=7d|28d|90d`,
   * default 28d). Read-only, Redis-cached 6 h per range; degrades to
   * `state:'disabled'` when GSC is off and `state:'error'` on a probe failure.
   * No-store (global default); never leaks an engine body or credential.
   */
  @Get(ADMIN_API_ROUTES.seo.analytics)
  @Permissions('seo:view')
  @RateLimit.Admin()
  @ApiOperation({ summary: 'Get Google Search Console analytics rollup' })
  getAnalytics(@Query() dto: GetSeoAnalyticsAdminDto) {
    return this.insights.getSearchAnalytics(dto.range);
  }

  /**
   * Per-product Google index-state readout (DR-17 D5) — GSC `urlInspection.index.inspect`
   * for one URL (a raw `?url=` or a `?productId=[&locale=]` resolved server-side).
   * READ-only: it reports Google's last-known index state, never a recrawl request
   * (research §1). Cached ≥24 h and guarded by the daily 2 000/property inspect
   * budget (returns `state:'exhausted'` when spent); degrades to `state:'disabled'`
   * when GSC is off. `seo:view`; No-store (global default); lazy-on-click only.
   */
  @Get(ADMIN_API_ROUTES.seo.urlInspection)
  @Permissions('seo:view')
  @RateLimit.Admin()
  @ApiOperation({ summary: 'Get Google index state for one URL' })
  inspectUrl(@Query() dto: InspectUrlAdminDto) {
    return this.insights.inspectUrl(dto);
  }

  /**
   * "Re-check now" (DR-17 D3) — the only live multi-engine submission-health probe
   * (GSC `sitemaps.list` + Bing `GetFeeds` + public-sitemap fetch). Refreshes the
   * cached snapshot the status strip reads. `seo:manage` + a 1 / 5-min throttle so a
   * held button can't hammer the engines (plan §8 + §11 #7). Returns 200 (action,
   * not a resource creation).
   */
  @Post(ADMIN_API_ROUTES.seo.healthRecheck)
  @Permissions('seo:manage')
  @RateLimit.SeoHealthRecheck()
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: 'Re-check live search engine submission health' })
  recheckHealth() {
    return this.insights.recheckHealth();
  }
}
