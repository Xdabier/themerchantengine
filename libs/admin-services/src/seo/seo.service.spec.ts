  // ── inspectUrl() (DR-17 D5) ──────────────────────────────────────────────────

  const inspectionOk = {
    state: 'ok',
    detail: 'PASS',
    url: 'https://demo.example/fr/catalog/product/fraise-dentaire',
    verdict: 'PASS',
    coverageState: 'Submitted and indexed',
    indexingState: 'INDEXING_ALLOWED',
    robotsTxtState: 'ALLOWED',
    pageFetchState: 'SUCCESSFUL',
    lastCrawlTime: '2026-06-27T10:00:00.000Z',
    googleCanonical: 'https://demo.example/fr/catalog/product/fraise-dentaire',
    userCanonical: 'https://demo.example/fr/catalog/product/fraise-dentaire',
    inspectUsed: null,
    inspectCap: null,
  };
  const inspectionNulls = {
    detail: '',
    url: null,
    verdict: null,
    coverageState: null,
    indexingState: null,
    robotsTxtState: null,
    pageFetchState: null,
    lastCrawlTime: null,
    googleCanonical: null,
    userCanonical: null,
    inspectUsed: null,
    inspectCap: null,
  };

  it('inspectUrl({url}) sends ?url= (no productId) with credentials', (done) => {
    const url = 'https://demo.example/fr/catalog/product/fraise-dentaire';
    service.inspectUrl({ url }).subscribe((i) => {
      expect(i.state).toBe('ok');
      expect(i.verdict).toBe('PASS');
      done();
    });
    const req = http.expectOne((r) => r.url === '/api/v1/admin/seo/url-inspection');
    expect(req.request.method).toBe('GET');
    expect(req.request.params.get('url')).toBe(url);
    expect(req.request.params.get('productId')).toBeNull();
    expect(req.request.params.get('locale')).toBeNull();
    expect(req.request.withCredentials).toBe(true);
    req.flush({ data: inspectionOk });
  });

  it('inspectUrl({productId}) sends ?productId= (no url)', (done) => {
    service.inspectUrl({ productId: 'cmprod01' }).subscribe((i) => {
      expect(i.state).toBe('disabled');
      done();
    });
    const req = http.expectOne((r) => r.url === '/api/v1/admin/seo/url-inspection');
    expect(req.request.params.get('productId')).toBe('cmprod01');
    expect(req.request.params.get('url')).toBeNull();
    req.flush({ data: { ...inspectionNulls, state: 'disabled', detail: 'GSC disabled' } });
  });

  it('inspectUrl({productId, locale}) includes ?locale=', (done) => {
    // The value has to be one the live `InspectUrlAdminDto` allowlist accepts.
    // This runs against a mocked transport, so a locale the API rejects would
    // keep passing here forever, which is exactly how the stale `'en' | 'ar'`
    // union on this method survived D2 flipping SUPPORTED_LOCALES to fr + en.
    service.inspectUrl({ productId: 'cmprod01', locale: 'fr' }).subscribe(() => done());
    const req = http.expectOne((r) => r.url === '/api/v1/admin/seo/url-inspection');
    expect(req.request.params.get('locale')).toBe('fr');
    req.flush({ data: inspectionOk });
  });

  it('inspectUrl() accepts the disabled degrade (all-null fields) as next, not error', (done) => {
    service.inspectUrl({ productId: 'cmprod01' }).subscribe({
      next: (i) => {
        expect(i.state).toBe('disabled');
        expect(i.verdict).toBeNull();
        done();
      },
      error: () => done.fail('disabled degrade must not error'),
    });
    http
      .expectOne('/api/v1/admin/seo/url-inspection?productId=cmprod01')
      .flush({ data: { ...inspectionNulls, state: 'disabled', detail: 'GSC disabled' } });
  });

