  // ── submitManual (DR-17 D2) ───────────────────────────────────────────────

  const submitResponseFixture = {
    dryRun: false,
    targetType: 'sitemap',
    requestedCount: 1,
    results: [
      {
        engine: 'gsc',
        accepted: true,
        submitted: 1,
        skippedDeduped: 0,
        reason: null,
        submissionId: 's1',
      },
      {
        engine: 'bing',
        accepted: true,
        submitted: 1,
        skippedDeduped: 0,
        reason: null,
        submissionId: 's2',
      },
    ],
  };

  it('submitManual({sitemap:true}) POSTs to /seo/submit with a UUID v4 idempotency key', (done) => {
    service.submitManual({ sitemap: true }).subscribe((res) => {
      expect(res.results.map((r) => r.engine)).toEqual(['gsc', 'bing']);
      done();
    });
    const req = http.expectOne('/api/v1/admin/seo/submit');
    expect(req.request.method).toBe('POST');
    expect(req.request.headers.get('X-Idempotency-Key')).toMatch(
      /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i,
    );
    req.flush({ data: submitResponseFixture });
  });

  it('submitManual() generates a different key on each call', () => {
    service.submitManual({ sitemap: true }).subscribe();
    service.submitManual({ sitemap: true }).subscribe();
    const reqs = http.match('/api/v1/admin/seo/submit');
    expect(reqs).toHaveLength(2);
    expect(reqs[0].request.headers.get('X-Idempotency-Key')).not.toBe(
      reqs[1].request.headers.get('X-Idempotency-Key'),
    );
    reqs.forEach((r) => r.flush({ data: submitResponseFixture }));
  });

  it('submitManual({productIds}) sends the productIds body', (done) => {
    const id = 'a4f5c9a4-1a1a-4a4a-8a8a-ab0000000001';
    service.submitManual({ productIds: [id] }).subscribe(() => done());
    const req = http.expectOne('/api/v1/admin/seo/submit');
    expect(req.request.body.productIds).toEqual([id]);
    req.flush({ data: { ...submitResponseFixture, targetType: 'products' } });
  });

  it('submitManual() rejects a payload with no target before any HTTP call', () => {
    expect(() => service.submitManual({} as never).subscribe()).toThrow();
    http.expectNone('/api/v1/admin/seo/submit');
  });

  it('submitManual() rejects a payload with two targets before any HTTP call', () => {
    expect(() =>
      service.submitManual({ sitemap: true, url: 'https://x/y' } as never).subscribe(),
    ).toThrow();
    http.expectNone('/api/v1/admin/seo/submit');
  });

  it('submitManual() treats submitted:0 / all-deduped as a success (next, not error)', (done) => {
    service.submitManual({ sitemap: true }).subscribe({
      next: (res) => {
        expect(res.results[0].submitted).toBe(0);
        done();
      },
      error: () => done.fail('all-deduped must be a success'),
    });
    http.expectOne('/api/v1/admin/seo/submit').flush({
      data: {
        dryRun: false,
        targetType: 'sitemap',
        requestedCount: 1,
        results: [
          {
            engine: 'gsc',
            accepted: true,
            submitted: 0,
            skippedDeduped: 0,
            reason: 'all deduped',
            submissionId: 's1',
          },
        ],
      },
    });
  });

  it('submitManual() throws a Zod error on a malformed response', (done) => {
    service.submitManual({ sitemap: true }).subscribe({
      next: () => done.fail('expected zod error'),
      error: () => done(),
    });
    http.expectOne('/api/v1/admin/seo/submit').flush({ data: { results: 'nope' } });
  });

  it('submitManual() propagates a backend 403', (done) => {
    service.submitManual({ sitemap: true }).subscribe({
      next: () => done.fail('expected error'),
      error: (err) => {
        expect(err.status).toBe(403);
        done();
      },
    });
    http
      .expectOne('/api/v1/admin/seo/submit')
      .flush({ error: { code: 'FORBIDDEN' } }, { status: 403, statusText: 'Forbidden' });
  });

