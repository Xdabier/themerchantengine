// ── GSC Search Analytics (DR-17 D4) ────────────────────────────────────────────

/** Allowlisted lookback windows — parity with the backend `SEO_ANALYTICS_RANGES`. */
export const seoAnalyticsRangeSchema = z.enum(['7d', '28d', '90d']);
export type SeoAnalyticsRange = z.infer<typeof seoAnalyticsRangeSchema>;

/** One row's four Search-Console metrics. Each metric is nullable so a brand-new
 * property (impressions but no clicks yet, or vice-versa) parses cleanly. */
export const seoAnalyticsMetricsSchema = z.object({
  clicks: z.number().nullable(),
  impressions: z.number().nullable(),
  ctr: z.number().nullable(),
  position: z.number().nullable(),
});
export type SeoAnalyticsMetrics = z.infer<typeof seoAnalyticsMetricsSchema>;

export const seoAnalyticsSeriesPointSchema = seoAnalyticsMetricsSchema.extend({
  date: z.string(),
});
export type SeoAnalyticsSeriesPoint = z.infer<typeof seoAnalyticsSeriesPointSchema>;

export const seoAnalyticsQueryRowSchema = seoAnalyticsMetricsSchema.extend({
  query: z.string(),
});
export type SeoAnalyticsQueryRow = z.infer<typeof seoAnalyticsQueryRowSchema>;

export const seoAnalyticsPageRowSchema = seoAnalyticsMetricsSchema.extend({
  page: z.string(),
});
export type SeoAnalyticsPageRow = z.infer<typeof seoAnalyticsPageRowSchema>;

/** Degrade-tolerant: `state` is the shared read-state union, `totals`/`asOf` are
 * nullable (disabled/error or a still-settling window), and the breakdown arrays
 * are plain arrays the backend always supplies (empty, never absent). `asOf` is a
 * plain `z.string()` (NOT `.datetime()`) so an off-spec GSC date never blanks the
 * block. */
export const seoAnalyticsSchema = z.object({
  state: seoEngineReadStateSchema,
  detail: z.string(),
  range: seoAnalyticsRangeSchema,
  asOf: z.string().nullable(),
  totals: seoAnalyticsMetricsSchema.nullable(),
  series: z.array(seoAnalyticsSeriesPointSchema),
  topQueries: z.array(seoAnalyticsQueryRowSchema),
  topPages: z.array(seoAnalyticsPageRowSchema),
});
export type SeoAnalytics = z.infer<typeof seoAnalyticsSchema>;

// ── Per-product URL Inspection (DR-17 D5) ──────────────────────────────────────

/** Inspection read state — its own 4-state union (adds `exhausted`, the daily
 * 2 000/property budget being spent) distinct from the 3-state
 * `seoEngineReadStateSchema` used by coverage/quota/analytics. */
export const seoUrlInspectionStateSchema = z.enum(['ok', 'disabled', 'error', 'exhausted']);
export type SeoUrlInspectionState = z.infer<typeof seoUrlInspectionStateSchema>;

/** One URL's GSC index state — a READ of Google's last-known verdict, never a
 * recrawl. Degrade-tolerant: every verdict field is nullable (a never-crawled URL,
 * or a disabled/error/exhausted state, carries nulls) so the badge always parses;
 * `lastCrawlTime` is a plain `z.string()` (not `.datetime()`) so an off-spec GSC
 * timestamp never blanks the badge. `inspectUsed`/`inspectCap` populate on the
 * `exhausted` state for the budget readout. */
export const seoUrlInspectionSchema = z.object({
  state: seoUrlInspectionStateSchema,
  detail: z.string(),
  url: z.string().nullable(),
  verdict: z.string().nullable(),
  coverageState: z.string().nullable(),
  indexingState: z.string().nullable(),
  robotsTxtState: z.string().nullable(),
  pageFetchState: z.string().nullable(),
  lastCrawlTime: z.string().nullable(),
  googleCanonical: z.string().nullable(),
  userCanonical: z.string().nullable(),
  inspectUsed: z.number().nullable(),
  inspectCap: z.number().nullable(),
});
export type SeoUrlInspection = z.infer<typeof seoUrlInspectionSchema>;
