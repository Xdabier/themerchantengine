// ── Manual reindex submit (DR-17 D2) ──────────────────────────────────────────

/**
 * Parity with the backend `SubmitSeoAdminDto`: target fields are individually
 * optional (mirroring the DTO), and the "exactly one target" cardinality is
 * enforced here by a refine so the client rejects a bad request before any HTTP
 * call — the backend orchestrator enforces the same rule server-side.
 */
export const submitSeoRequestSchema = z
  .object({
    // require_tld: false on the backend @IsUrl — accepts localhost-style URLs;
    // Zod's WHATWG URL validator is equally permissive, so parity holds.
    url: z.string().url().optional(),
    // .max mirrors the backend @ArrayMaxSize(SEO_SUBMIT_MAX_PRODUCT_IDS = 500).
    // Product IDs are CUIDs (not UUID v4), so z.string() is correct here.
    productIds: z.array(z.string().min(1)).min(1).max(500).optional(),
    sitemap: z.literal(true).optional(),
    engines: z.array(seoSubmissionEngineSchema).min(1).optional(),
    dryRun: z.boolean().optional(),
  })
  .refine((v) => [v.url, v.productIds, v.sitemap].filter((x) => x !== undefined).length === 1, {
    message: 'Provide exactly one target: url, productIds, or sitemap.',
  });
export type SubmitSeoRequest = z.infer<typeof submitSeoRequestSchema>;

export const submitSeoEngineResultSchema = z.object({
  engine: seoSubmissionEngineSchema,
  accepted: z.boolean(),
  submitted: z.number().int().nonnegative(),
  skippedDeduped: z.number().int().nonnegative(),
  reason: z.string().nullable(),
  submissionId: z.string().nullable(),
});
export type SubmitSeoEngineResult = z.infer<typeof submitSeoEngineResultSchema>;

export const submitSeoResponseSchema = z.object({
  dryRun: z.boolean(),
  targetType: seoSubmissionTargetTypeSchema,
  requestedCount: z.number().int().nonnegative(),
  results: z.array(submitSeoEngineResultSchema),
});
export type SubmitSeoResponse = z.infer<typeof submitSeoResponseSchema>;

// ── Monitoring reads (DR-17 D3) ────────────────────────────────────────────────

/** Read-side per-engine state for coverage/quota: ok (live) | disabled | error. */
export const seoEngineReadStateSchema = z.enum(['ok', 'disabled', 'error']);
export type SeoEngineReadState = z.infer<typeof seoEngineReadStateSchema>;

/** Submission-health snapshot states (DR-16). Parity with the backend
 * `SubmissionHealthState`. */
export const submissionHealthStateSchema = z.enum(['ok', 'stale', 'error', 'missing', 'disabled']);
export type SubmissionHealthState = z.infer<typeof submissionHealthStateSchema>;

/** The cached submission-health snapshot the status strip renders + the live
 * `recheckHealth()` response. `checkedAt` is ISO 8601 (kept as a plain string so
 * a slightly off-spec timestamp never fails the parse and blanks the strip). */
export const submissionHealthSchema = z.object({
  checkedAt: z.string(),
  healthy: z.boolean(),
  gsc: z.object({ state: submissionHealthStateSchema, detail: z.string() }),
  bing: z.object({ state: submissionHealthStateSchema, detail: z.string() }),
  publicSitemap: z.object({ state: z.enum(['ok', 'error']), detail: z.string() }),
});
export type SubmissionHealth = z.infer<typeof submissionHealthSchema>;

