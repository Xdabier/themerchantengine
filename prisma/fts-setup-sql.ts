import {
  getLocaleDefinition,
  registryLocaleCodes,
  type LocaleDefinition,
} from '../libs/shared/common/src/locale/locale-registry';

/**
 * Builds `prisma/search_fts_setup.sql` from the locale registry (DR-33). The
 * committed file is the output of `npm run db:fts:generate`, and
 * `__tests__/fts-setup-sql.spec.ts` fails when the two drift, so the psql prod
 * path and the install stepper keep piping a plain file.
 *
 * Every registry locale gets its own weighted segment, using the locale's
 * `textSearchConfig`, and its own trigram indexes. The `default` key of a
 * Translatable is folded into the English segment, or into the first locale
 * when English is not registered.
 */
type SearchLocale = Pick<LocaleDefinition, 'code' | 'direction' | 'textSearchConfig'>;

const CODE_PATTERN = /^[a-z][a-z0-9-]*$/;
const CONFIG_PATTERN = /^[a-z][a-z0-9_]*$/;
const DESCRIPTION_CAP = 10000;

type SegmentField = { column: string; weight: 'A' | 'B' | 'D'; cap?: number };

const NAME: SegmentField = { column: 'NEW.name', weight: 'A' };
const SHORT_DESCRIPTION: SegmentField = { column: 'NEW."shortDescription"', weight: 'B' };
const DESCRIPTION: SegmentField = { column: 'NEW.description', weight: 'D', cap: DESCRIPTION_CAP };

function assertSafe(locales: readonly SearchLocale[]): void {
  if (locales.length === 0) {
    throw new Error('FTS setup needs at least one locale');
  }
  for (const locale of locales) {
    if (!CODE_PATTERN.test(locale.code)) {
      throw new Error(`FTS setup: locale code "${locale.code}" is not a plain identifier`);
    }
    if (!CONFIG_PATTERN.test(locale.textSearchConfig)) {
      throw new Error(
        `FTS setup: text search config "${locale.textSearchConfig}" of ${locale.code} is not a plain identifier`,
      );
    }
  }
}

function segment(field: SegmentField, locale: SearchLocale, foldDefault: boolean): string {
  const own = `COALESCE(${field.column}->>'${locale.code}', '')`;
  const text = foldDefault ? `COALESCE(${field.column}->>'default', '') || ' ' || ${own}` : own;
  const capped = field.cap
    ? `left(\n            ${text},\n            ${field.cap}\n          )`
    : text;
  // Accents are stripped for Latin text only, so Arabic letters stay untouched.
  const body = locale.direction === 'ltr' ? `unaccent(${capped})` : capped;
  return [
    '    setweight(',
    `      to_tsvector('${locale.textSearchConfig}',`,
    `        ${body}`,
    `      ), '${field.weight}'`,
    '    )',
  ].join('\n');
}

function vectorExpression(locales: readonly SearchLocale[]): string {
  const defaultHolder = locales.find((locale) => locale.code === 'en') ?? locales[0];
  const parts: string[] = [];
  for (const field of [NAME, SHORT_DESCRIPTION]) {
    for (const locale of locales) {
      parts.push(
        `    -- ${field.column.replace('NEW.', '').replace(/"/g, '')} (${locale.code})\n${segment(field, locale, locale === defaultHolder)}`,
      );
    }
  }
  parts.push(
    [
      '    -- tags array: weight C (COALESCE the array so NULL tags give an empty string, not NULL)',
      '    setweight(',
      "      to_tsvector('simple',",
      "        unaccent(array_to_string(COALESCE(NEW.tags, ARRAY[]::text[]), ' '))",
      "      ), 'C'",
      '    )',
    ].join('\n'),
  );
  for (const locale of locales) {
    parts.push(
      `    -- description (${locale.code})\n${segment(DESCRIPTION, locale, locale === defaultHolder)}`,
    );
  }
  return parts.join(' ||\n');
}

function trigramIndexes(table: string, locales: readonly SearchLocale[]): string {
  const keys = ['default', ...locales.map((locale) => locale.code)];
  return keys
    .map(
      (key) =>
        `CREATE INDEX IF NOT EXISTS "${table}_name_${key}_trgm_idx"\n  ON "${table}" USING GIN (("name"->>'${key}') gin_trgm_ops);`,
    )
    .join('\n');
}

const HEADER = `-- =============================================================================
-- Search Full-Text Search Setup
-- GENERATED by \`npm run db:fts:generate\` from the locale registry
-- (libs/shared/common/src/locale/locale-registry.ts). Do not edit by hand: add
-- a language to the registry and regenerate. A drift spec fails when the two
-- disagree.
--
-- Re-apply after EVERY \`prisma db push\` (not managed by the Prisma schema, so
-- a push drops \`searchVector\` and its GIN index every time). \`npm run db:fts\`
-- on dev and test; \`psql -U postgres -f -\` as the superuser on prod, because
-- the app role can neither CREATE EXTENSION nor replace a postgres-owned
-- function. Requires PostgreSQL 12+.
--
-- ROLLBACK
--   The file is fully idempotent and ends with its own backfill, so reverting
--   it is a checkout plus a re-apply. There is no partial state to unwind:
--
--     git checkout <previous-sha> -- prisma/search_fts_setup.sql
--     npm run db:fts            # dev / test
--
--   On prod, pipe the reverted file through the pg container as superuser per
--   \`deploy/README.md\`. The re-apply restores the previous trigger body and
--   re-runs \`UPDATE "Product" SET name = name\` so every vector is rebuilt under
--   the old configuration.
--
-- LOCKING
--   \`prisma/apply-fts-setup.ts\` submits this whole file as one simple-query
--   batch, which Postgres wraps in a single implicit transaction, so every
--   index build and the terminal backfill hold their locks on "Product",
--   "Category" and "Brand" together until the file commits. The prod \`psql\`
--   path auto-commits per statement and holds them one at a time. At current
--   catalogue size this is seconds either way, but pick the window with the
--   batching in mind.
-- =============================================================================`;

export function buildFtsSetupSql(locales: readonly SearchLocale[]): string {
  assertSafe(locales);
  const weights = locales.map((locale) => locale.code).join(', ');
  return `${HEADER}

-- 1. Enable trigram extension (used for similarity() and fuzzy matching)
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- 2. Enable unaccent extension (strips accents for better matching)
CREATE EXTENSION IF NOT EXISTS unaccent;

-- =============================================================================
-- 3. Add searchVector column to Product (not in Prisma schema, trigger-managed)
-- =============================================================================

ALTER TABLE "Product"
  ADD COLUMN IF NOT EXISTS "searchVector" tsvector;

-- =============================================================================
-- 4. Trigger function: rebuilds searchVector on INSERT / UPDATE
--    Locales: ${weights}
--    Weights:
--      A (highest) - product name
--      B           - short description
--      C           - tags (array joined)
--      D (lowest)  - description body
-- =============================================================================

CREATE OR REPLACE FUNCTION product_search_vector_update()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- NULL-safety is critical: tsvector concatenation (\`||\`) yields NULL if ANY
  -- operand is NULL, and a NULL searchVector never matches \`@@\`, so the product
  -- becomes silently unsearchable. \`array_to_string(NULL, ' ')\` returns NULL
  -- (not '') when tags IS NULL. Every operand below is therefore COALESCE-guarded,
  -- and the whole expression is wrapped in COALESCE(..., ''::tsvector) so the
  -- column is never NULL regardless of input shape.
  NEW."searchVector" := COALESCE(
${vectorExpression(locales)},
    ''::tsvector
  );
  RETURN NEW;
END;
$$;

-- 5. Attach trigger to Product table
DROP TRIGGER IF EXISTS product_search_vector_trig ON "Product";
CREATE TRIGGER product_search_vector_trig
  BEFORE INSERT OR UPDATE OF name, description, "shortDescription", tags
  ON "Product"
  FOR EACH ROW
  EXECUTE FUNCTION product_search_vector_update();

-- =============================================================================
-- 6. Indexes
-- =============================================================================

-- GIN index on tsvector (FTS)
CREATE INDEX IF NOT EXISTS "Product_searchVector_gin_idx"
  ON "Product" USING GIN ("searchVector");

-- One trigram index per name key (the default plus every registry locale): the
-- query side probes the store's runtime default locale, so every one of them
-- needs an index or the similarity() scan runs unindexed on an anonymous
-- endpoint. Category and Brand names resolve at query time, so they get the
-- same set (the trigger cannot cheaply track brand or category renames).
${trigramIndexes('Product', locales)}

${trigramIndexes('Category', locales)}

${trigramIndexes('Brand', locales)}

-- Reference / code search: customer-facing variant SKU + product MPN / GTIN.
-- text_pattern_ops backs \`LOWER(col) = x\` and \`LOWER(col) LIKE 'prefix%'\`.
-- Codes are matched exact / prefix (NOT fuzzy) to avoid trigram false
-- positives between adjacent codes (e.g. SKU-123 vs SKU-124).
CREATE INDEX IF NOT EXISTS "ProductVariant_sku_lower_idx"
  ON "ProductVariant" (LOWER(sku) text_pattern_ops);
CREATE INDEX IF NOT EXISTS "Product_mpn_lower_idx"
  ON "Product" (LOWER(COALESCE(mpn, '')) text_pattern_ops);
CREATE INDEX IF NOT EXISTS "Product_gtin_lower_idx"
  ON "Product" (LOWER(COALESCE(gtin, '')) text_pattern_ops);

-- =============================================================================
-- 7. Backfill: populate searchVector for all existing products
--    (The trigger only fires on new INSERT/UPDATE, so backfill manually)
-- =============================================================================

-- Touch the \`name\` column so the BEFORE UPDATE OF name trigger fires for every row.
-- (The trigger is bound to specific columns; updating updatedAt alone does not fire it.)
UPDATE "Product"
SET name = name
WHERE "deletedAt" IS NULL;

-- =============================================================================
-- 8. Guard: fail loudly if any active product is still missing its
--    searchVector after the backfill. This is the regression tripwire for
--    "FTS not (re-)applied after the last bulk import", the failure that left
--    601/760 products unsearchable. Under psql (the prod apply path) each
--    statement auto-commits, so this RAISE fails the job WITHOUT rolling back
--    the committed backfill above; run psql with \`-v ON_ERROR_STOP=1\` so the
--    RAISE propagates a non-zero exit. (With the NULL-safe trigger above a
--    valid catalogue never trips this; it only fires on a genuine setup fault.)
-- =============================================================================
DO $$
DECLARE
  missing int;
BEGIN
  SELECT count(*) INTO missing
  FROM "Product"
  WHERE status = 'ACTIVE' AND "deletedAt" IS NULL AND "searchVector" IS NULL;

  IF missing > 0 THEN
    RAISE EXCEPTION
      'FTS guard: % active product(s) have NULL searchVector after backfill, re-run prisma/search_fts_setup.sql after the last bulk import', missing;
  END IF;
END $$;
`;
}

export function buildFtsSetupSqlFromRegistry(): string {
  const locales = registryLocaleCodes().map((code) => getLocaleDefinition(code));
  return buildFtsSetupSql(
    locales.filter((locale): locale is LocaleDefinition => locale !== undefined),
  );
}
