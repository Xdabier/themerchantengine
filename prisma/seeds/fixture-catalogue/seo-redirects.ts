import { RedirectType, type PrismaClient } from '@prisma/client';

import type { StoreRuntimeConfig } from '../../../libs/shared/common/src/store-config-fixtures/store-config-fixture.schema';

/**
 * One retired path per served locale, so the SSR smoke's redirect leg has a row
 * to probe (plan E2.6).
 *
 * That leg exists because every `SeoRedirect` row was inert for a while: the
 * rows hold storefront paths but the middleware was mounted on the API, which
 * nginx never routes a storefront path to. The check that was supposed to catch
 * it only ever asked whether the redirect TARGET resolved, so it reported green
 * against a table full of redirects that redirected nothing.
 *
 * The leg refuses to pass on an empty table rather than reporting green, which
 * is the right call and which is why the seed has to carry a row: without one
 * the guard cannot ask its question, and a harness that cannot ask is not the
 * same as a harness that got a good answer.
 *
 * `fromPath` is a path the catalogue does not serve and `toPath` one it does,
 * so the row is a real redirect rather than a self-reference.
 */
export const RETIRED_PATH_SEGMENT = 'retired-collection';

export async function seedSeoRedirects(
  prisma: PrismaClient,
  config: StoreRuntimeConfig,
): Promise<{ redirects: number }> {
  let redirects = 0;
  for (const locale of config.localization.supportedLocales) {
    const fromPath = `/${locale}/${RETIRED_PATH_SEGMENT}`;
    const toPath = `/${locale}/catalog`;
    const data = { toPath, type: RedirectType.MOVED_PERMANENTLY, isAutoGenerated: false };
    await prisma.seoRedirect.upsert({
      where: { fromPath },
      update: data,
      create: { fromPath, ...data },
    });
    redirects += 1;
  }
  return { redirects };
}
